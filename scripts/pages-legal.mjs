function artBody(ps) {
  const sub = ps.filter((p) => p.startsWith("("));
  const main = ps.filter((p) => !p.startsWith("("));
  const subHtml = sub.length ? `<ul class="plain">${sub.map((p) => `<li>${esc(p)}</li>`).join("")}</ul>` : "";
  if (main.length === 1) return `<p>${esc(main[0])}</p>${subHtml}`;
  return `<ol>${main.map((p) => `<li>${esc(p)}</li>`).join("")}</ol>${subHtml}`;
}

